def josa(word, pair="을/를"):
    """받침 유무로 조사 선택: 상장→상장을, 우수상→우수상을, 트로피→트로피를"""
    a, b = pair.split("/")
    ch = (word or "").strip()[-1:] or "가"
    if "가" <= ch <= "힣":
        return word + (a if (ord(ch) - 0xAC00) % 28 else b)
    return word + a


def fill(text, kind):
    return text.replace("{상을}", josa(kind or "상장"))


def phrases_for(kind):
    """종류에 맞는 문구 목록 [(label, text)]. 목록에 없는 종류(직접 입력)는 상장 문구를 그 이름으로."""
    base = PHRASES.get(kind) or PHRASES["상장"]
    return [(lab, fill(t, kind)) for lab, t in base]
